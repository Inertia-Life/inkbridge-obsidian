const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const converter = require('./conversion.js');
const {DOMParser} = require('linkedom');
global.DOMParser = class { parseFromString(html) { return new DOMParser().parseFromString('<html><body>'+html+'</body></html>', 'text/html'); } };
const ids = ['input','output','inputCount','outputCount','status','toast','imageSaveBtn','imageStatus','pasteBtn','copyBtn','downloadBtn','clearBtn','sampleBtn'];
const elements = Object.fromEntries(ids.map(id => [id, {value:'', textContent:'', hidden:false, selectionStart:0, selectionEnd:0, classList:{add(){},remove(){}}, listeners:{}, addEventListener(type, fn){this.listeners[type]=fn}, focus(){}, setRangeText(text){this.value+=text}}]));
const writes = [];
const context = {document:{getElementById:id=>elements[id], createElement:()=>({click(){}})}, window:{showDirectoryPicker:async()=>({getDirectoryHandle:async(name)=>{if(name==='.obsidian')return {}; assert.equal(name,'墨桥附件'); return {getFileHandle:async(file)=>({createWritable:async()=>({write:async(blob)=>writes.push({file, blob}),close:async()=>{}})})}}})}, navigator:{}, ObsidianConverter:converter, Blob, Uint8Array, atob, URL, setTimeout:()=>1, clearTimeout(){}, console};
vm.runInNewContext(fs.readFileSync(require.resolve('./app.js'),'utf8'), context);
(async()=>{
  const blob = new Blob(['picture'], {type:'image/png'});
  let prevented = false;
  elements.input.listeners.paste({preventDefault(){prevented=true}, clipboardData:{getData(type){return type==='text/plain'?'附图':''},items:[{kind:'file',type:'image/png',getAsFile:()=>blob}]}});
  assert.ok(prevented);
  assert.match(elements.output.value, /附图[\s\S]*图片待保存/);
  assert.equal(elements.imageSaveBtn.hidden,false);
  await elements.imageSaveBtn.listeners.click();
  assert.equal(writes.length,1);
  assert.match(writes[0].file,/^inkbridge-.+\.png$/);
  assert.equal(await writes[0].blob.text(),'picture');
  assert.match(elements.output.value,/!\[\[墨桥附件\/inkbridge-.+\.png\]\]/);
  assert.equal(elements.imageSaveBtn.hidden,true);
  elements.clearBtn.listeners.click();
  elements.input.listeners.paste({preventDefault(){}, clipboardData:{getData(type){return type==='text/html'?'<p>图文</p><img src="blob:first"><img src="blob:second">':''},items:[{kind:'file',type:'image/png',getAsFile:()=>blob}]}});
  assert.equal((elements.output.value.match(/图片数据未能提取/g)||[]).length,2);
  assert.equal(elements.imageSaveBtn.hidden,true);
  elements.clearBtn.listeners.click();
  elements.input.listeners.paste({preventDefault(){}, clipboardData:{getData(){return ''},items:[{kind:'file',type:'image/png',getAsFile:()=>blob}]}});
  context.window.showDirectoryPicker=async()=>({getDirectoryHandle:async()=>{throw Object.assign(new Error('not found'),{name:'NotFoundError'})}});
  await elements.imageSaveBtn.listeners.click();
  assert.match(elements.output.value,/图片待保存/);
  assert.match(elements.imageStatus.textContent,/不是 Obsidian 仓库/);
  assert.equal(writes.length,1);
  console.log('Clipboard image save test passed');
})().catch(error=>{console.error(error);process.exitCode=1});
